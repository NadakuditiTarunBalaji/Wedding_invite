const gate = document.querySelector("#language-gate");
const invitation = document.querySelector("#invitation");
const switchButton = document.querySelector("#language-switch");
const countdown = document.querySelector("#countdown");
const hero = document.querySelector(".hero");
const envelope = document.querySelector(".envelope-scene");
const parallaxSections = document.querySelectorAll(".parallax-section");
const dateCard = document.querySelector(".date-card");
const progressFill = document.querySelector("#scroll-progress-fill");
const languageGate = document.querySelector("#language-gate");
const cinematicStage = document.querySelector("#cinematic-stage");
const scenes = [...document.querySelectorAll(".scene")];
let language = "en";
let parallaxFrame = 0;
let currentScene = 0;
let sceneChanging = false;
let touchStartY = 0;
let gateTouchStartY = 0;
let gateScrollProgress = 0;

document.body.classList.add("gate-locked");
languageGate.classList.remove("language-ready");
languageGate.style.setProperty("--gate-progress", "0");

function revealLanguageSelection() {
  const progress = languageGate.classList.contains("language-ready") ? 1 : 0;
  languageGate.style.setProperty("--gate-progress", progress.toFixed(3));
}

function applyLanguage(nextLanguage) {
  language = nextLanguage;
  document.documentElement.lang = nextLanguage === "te" ? "te" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translations[nextLanguage][element.dataset.i18n];
  });
  if (switchButton) {
    switchButton.querySelector("span").textContent =
      nextLanguage === "en" ? "తెలుగు" : "English";
  }
  updateCountdown();
}

function enterInvitation(nextLanguage) {
  applyLanguage(nextLanguage);
  if (gate) gate.hidden = true;
  if (invitation) invitation.hidden = false;
  document.body.classList.remove("gate-locked");
  document.body.classList.add("cinematic-locked");
  window.scrollTo(0, 0);
  showScene(0);
}

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", (event) => {
    event.preventDefault();
    event.stopPropagation();
    enterInvitation(button.dataset.language);
  });
});

if (switchButton) {
  switchButton.addEventListener("click", () =>
    applyLanguage(language === "en" ? "te" : "en"),
  );
}

function showScene(index) {
  const nextIndex = Math.min(scenes.length - 1, Math.max(0, index));
  if (
    nextIndex === currentScene &&
    scenes[currentScene].classList.contains("is-active")
  )
    return;
  scenes.forEach((scene, sceneIndex) => {
    scene.classList.toggle("is-active", sceneIndex === nextIndex);
    scene.classList.toggle(
      "is-exiting",
      sceneIndex === currentScene && sceneIndex !== nextIndex,
    );
  });
  currentScene = nextIndex;
}

function changeScene(direction) {
  if (sceneChanging) return;
  const nextIndex = Math.min(
    scenes.length - 1,
    Math.max(0, currentScene + direction),
  );
  if (nextIndex === currentScene) return;
  sceneChanging = true;
  showScene(nextIndex);
  window.setTimeout(() => {
    sceneChanging = false;
  }, 700);
}

function handleSceneWheel(event) {
  event.preventDefault();
  if (Math.abs(event.deltaY) > 8) changeScene(event.deltaY > 0 ? 1 : -1);
}

cinematicStage.addEventListener("wheel", handleSceneWheel, { passive: false });
document.addEventListener(
  "wheel",
  (event) => {
    if (document.body.classList.contains("cinematic-locked"))
      handleSceneWheel(event);
  },
  { passive: false },
);

cinematicStage.addEventListener(
  "touchstart",
  (event) => {
    touchStartY = event.changedTouches[0].clientY;
  },
  { passive: true },
);

cinematicStage.addEventListener(
  "touchend",
  (event) => {
    const distance = touchStartY - event.changedTouches[0].clientY;
    if (Math.abs(distance) > 35) changeScene(distance > 0 ? 1 : -1);
  },
  { passive: true },
);

function revealLanguageOnInput() {
  gateScrollProgress = 1;
  languageGate.classList.add("language-ready");
  revealLanguageSelection();
}

languageGate.addEventListener(
  "wheel",
  (event) => {
    event.preventDefault();
    if (event.deltaY > 8) {
      gateScrollProgress = Math.min(
        1,
        gateScrollProgress + Math.min(event.deltaY, 420) / 1400,
      );
      languageGate.style.setProperty(
        "--gate-progress",
        gateScrollProgress.toFixed(3),
      );
      if (gateScrollProgress >= 1) revealLanguageOnInput();
    }
  },
  { passive: false },
);

languageGate.addEventListener(
  "touchstart",
  (event) => {
    gateTouchStartY = event.changedTouches[0].clientY;
  },
  { passive: true },
);

languageGate.addEventListener(
  "touchend",
  (event) => {
    if (gateTouchStartY - event.changedTouches[0].clientY > 35)
      revealLanguageOnInput();
  },
  { passive: true },
);

document.addEventListener("keydown", (event) => {
  if (
    !gate.hidden &&
    (event.key === "ArrowDown" || event.key === "PageDown" || event.key === " ")
  ) {
    revealLanguageOnInput();
    return;
  }
  if (!document.body.classList.contains("cinematic-locked")) return;
  if (
    event.key === "ArrowDown" ||
    event.key === "PageDown" ||
    event.key === " "
  )
    changeScene(1);
  if (event.key === "ArrowUp" || event.key === "PageUp") changeScene(-1);
});

function observeReveals() {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.12 },
  );
  document
    .querySelectorAll(".reveal")
    .forEach((element) => observer.observe(element));
}

function updateParallax() {
  parallaxFrame = 0;
  if (!hero || !envelope) return;

  const viewportHeight = window.innerHeight;
  const getScrollProgress = (element) => {
    const scrollDistance = element.offsetHeight - viewportHeight;
    if (scrollDistance <= 0) return 0;
    const progress = -element.getBoundingClientRect().top / scrollDistance;
    return Math.min(1, Math.max(0, progress));
  };

  hero.style.setProperty("--hero-progress", getScrollProgress(hero).toFixed(3));
  envelope.style.setProperty(
    "--envelope-progress",
    getScrollProgress(envelope).toFixed(3),
  );

  if (progressFill) {
    const totalScroll = document.documentElement.scrollHeight - viewportHeight;
    const progress = totalScroll > 0 ? (window.scrollY / totalScroll) * 100 : 0;
    progressFill.style.height = `${Math.min(100, Math.max(0, progress))}%`;
  }

  parallaxSections.forEach((section) => {
    const rect = section.getBoundingClientRect();
    const progress =
      (viewportHeight - rect.top) / (viewportHeight + rect.height);
    section.style.setProperty(
      "--section-progress",
      Math.min(1, Math.max(0, progress)).toFixed(3),
    );
  });

  if (dateCard) {
    const rect = dateCard.getBoundingClientRect();
    const progress =
      (viewportHeight - rect.top) / (viewportHeight + rect.height);
    dateCard.style.setProperty(
      "--section-progress",
      Math.min(1, Math.max(0, progress)).toFixed(3),
    );
  }
}

function requestParallaxUpdate() {
  if (!parallaxFrame) parallaxFrame = requestAnimationFrame(updateParallax);
}

window.addEventListener("scroll", requestParallaxUpdate, { passive: true });
window.addEventListener("scroll", revealLanguageSelection, { passive: true });
window.addEventListener("resize", requestParallaxUpdate);
requestParallaxUpdate();
revealLanguageSelection();

function updateCountdown() {
  const weddingDate = new Date("2026-10-25T07:45:00+05:30");
  const difference = weddingDate - new Date();
  if (difference <= 0) {
    if (countdown) {
      countdown.textContent =
        language === "te"
          ? "శుభ ముహూర్తం ప్రారంభమైంది"
          : "The celebrations have begun";
    }
    return;
  }
  const days = Math.floor(difference / 86400000);
  const hours = Math.floor((difference / 3600000) % 24);
  const minutes = Math.floor((difference / 60000) % 60);
  const seconds = Math.floor((difference / 1000) % 60);
  if (countdown) {
    countdown.textContent =
      language === "te"
        ? `${days} రోజులు · ${hours} గంటలు · ${minutes} నిమిషాలు · ${seconds} సెకన్లు`
        : `${days} days · ${hours} hours · ${minutes} minutes · ${seconds} seconds to go`;
  }
}

setInterval(updateCountdown, 1000);
updateCountdown();
showScene(0);
